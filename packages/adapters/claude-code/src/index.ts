import type { NativeRunConfig, NativeEvent } from '../../../contracts/src/native.js';

export const requiredFlags = [
  '--bare',
  '--restricted',
  '--tools',
  '--permission-mode',
  '--max-turns',
  '--max-budget-usd',
  '--strict-mcp-config',
  '--no-session-persistence',
];
export const requiredSessionFlags = ['--session-id', '--resume'];
/** 2.1.283 accepts --max-turns but omits it from --help. Keep this exception
 * version-specific; never waive missing restriction flags or infer model access. */
export function claudeCapabilities(version: string, help: string, retainSessions = false): boolean {
  const documentedHiddenTurns = version.trim() === '2.1.283 (Claude Code)';
  return (
    !!version.trim() &&
    [...requiredFlags, ...(retainSessions ? requiredSessionFlags : [])].every(
      (flag) => help.includes(flag) || (documentedHiddenTurns && flag === '--max-turns'),
    )
  );
}
/** Native IDs are generated by the node, never accepted from browser input. */
export interface ClaudeSessionSelection {
  sessionId: string;
  action: 'created' | 'resumed';
}
export function claudeSessionId(value: string): string {
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value))
    throw new Error('Invalid Claude session UUID');
  return value;
}
export function claudeArguments(
  config: NativeRunConfig,
  session?: ClaudeSessionSelection,
): string[] {
  const tools = config.mode === 'edit' ? 'Read,Glob,Grep,Edit,Write' : 'Read,Glob,Grep';
  const deniedFiles = [
    '.env',
    '.env.*',
    '**/.env',
    '**/.env.*',
    '**/*.pem',
    '**/*.key',
    '**/credentials*',
    '.hexu/**',
    '.git/**',
    '.ssh/**',
  ];
  const settings = {
    permissions: {
      deny: deniedFiles.flatMap((path) =>
        ['Read', 'Edit', 'Write'].map((tool) => `${tool}(./${path})`),
      ),
    },
  };
  return [
    '--bare',
    '--restricted',
    ...(session
      ? [
          session.action === 'resumed' ? '--resume' : '--session-id',
          claudeSessionId(session.sessionId),
        ]
      : ['--no-session-persistence']),
    '-p',
    '--output-format',
    'stream-json',
    '--verbose',
    '--permission-mode',
    'dontAsk',
    '--tools',
    tools,
    '--allowedTools',
    tools,
    '--strict-mcp-config',
    '--mcp-config',
    '{"mcpServers":{}}',
    '--settings',
    JSON.stringify(settings),
    '--max-turns',
    String(config.maxTurns),
    '--max-budget-usd',
    String(config.maxBudgetUsd),
    ...(config.model ? ['--model', config.model] : []),
  ];
}
export interface ClaudeSummary {
  resultReceived: boolean;
  success: boolean;
  text: string;
  sessionId?: string;
  resolvedModel?: string;
  initialized?: boolean;
  denials: number;
}
export interface ClaudeSessionGuard {
  sessionId: string;
  cwd: string;
  mode: NativeRunConfig['mode'];
  resolvedModel?: string;
}
/** Decode documented JSONL messages, never infer success from prose or a zero exit code alone. */
export class ClaudeStream {
  readonly summary: ClaudeSummary = { resultReceived: false, success: false, text: '', denials: 0 };
  private eventCount = 0;
  constructor(
    private emit: (kind: NativeEvent['kind'], text: string) => void,
    private session?: ClaudeSessionGuard,
  ) {
    if (session) claudeSessionId(session.sessionId);
  }
  private guard(message: Record<string, unknown>) {
    const expected = this.session;
    if (!expected) return;
    const init = message.type === 'system' && message.subtype === 'init';
    if (this.summary.resultReceived) throw new Error('Event after terminal result');
    if (message.session_id !== undefined && message.session_id !== expected.sessionId)
      throw new Error('Claude session identity changed');
    if (init) {
      const tools =
        expected.mode === 'edit'
          ? ['Read', 'Glob', 'Grep', 'Edit', 'Write']
          : ['Read', 'Glob', 'Grep'];
      if (
        this.summary.initialized ||
        message.session_id !== expected.sessionId ||
        message.cwd !== expected.cwd ||
        message.permissionMode !== 'dontAsk' ||
        typeof message.model !== 'string' ||
        !message.model ||
        message.model.length > 200 ||
        (expected.resolvedModel && message.model !== expected.resolvedModel) ||
        !Array.isArray(message.tools) ||
        message.tools.some((tool) => !tools.includes(String(tool))) ||
        !Array.isArray(message.mcp_servers) ||
        message.mcp_servers.length !== 0
      )
        throw new Error('Claude session initialization is incompatible');
      this.summary.initialized = true;
      this.summary.resolvedModel = message.model;
    } else if (message.type === 'assistant' || message.type === 'result') {
      if (!this.summary.initialized || message.session_id !== expected.sessionId)
        throw new Error('Claude output has no matching initialization');
    }
  }
  line(line: string) {
    if (++this.eventCount > 2000) throw new Error('event limit');
    const event: unknown = JSON.parse(line);
    if (!event || typeof event !== 'object' || !('type' in event)) throw new Error('invalid event');
    const message = event as Record<string, unknown>;
    this.guard(message);
    if (message.session_id !== undefined) {
      if (
        typeof message.session_id !== 'string' ||
        !/^[a-zA-Z0-9_-]{1,200}$/.test(message.session_id) ||
        (this.summary.sessionId && this.summary.sessionId !== message.session_id)
      )
        throw new Error('Invalid or inconsistent Claude session identity');
      this.summary.sessionId = message.session_id;
    }
    if (message.type === 'system' && message.subtype === 'init') {
      if (typeof message.session_id === 'string')
        this.summary.sessionId = message.session_id.slice(0, 200);
      this.emit('status', '原生工具已开始本次会话');
    } else if (message.type === 'system' && message.subtype === 'permission_denied') {
      this.summary.denials++;
      this.emit('warning', '原生权限规则拒绝了一项操作；不会在网页自动扩权');
    } else if (message.type === 'assistant') {
      const content = (message.message as { content?: unknown } | undefined)?.content;
      if (Array.isArray(content))
        for (const block of content) {
          if (!block || typeof block !== 'object') continue;
          if (block.type === 'text' && typeof block.text === 'string')
            this.emit('text', block.text.slice(0, 12000));
          if (block.type === 'tool_use')
            this.emit('tool', `工具调用：${String(block.name).slice(0, 80)}`);
          // Never expose raw thinking, tool arguments or full file bodies by default.
        }
    } else if (message.type === 'result') {
      if (this.summary.resultReceived) throw new Error('duplicate result');
      this.summary.resultReceived = true;
      this.summary.success = message.subtype === 'success' && message.is_error !== true;
      this.summary.text = typeof message.result === 'string' ? message.result.slice(0, 20000) : '';
      if (typeof message.session_id === 'string')
        this.summary.sessionId = message.session_id.slice(0, 200);
      if (Array.isArray(message.permission_denials))
        this.summary.denials = Math.max(this.summary.denials, message.permission_denials.length);
      if (typeof message.total_cost_usd === 'number' && Number.isFinite(message.total_cost_usd))
        this.emit(
          'usage',
          `工具报告的估算费用：USD ${message.total_cost_usd}。不是实际账单。${this.session?.resolvedModel ? '恢复会话的统计范围尚未实测，不将此值重复累计为本轮费用。' : ''}`,
        );
      if (!this.summary.success)
        this.emit(
          'warning',
          `执行未正常完成：${String(message.subtype ?? 'unknown').slice(0, 100)}`,
        );
    }
    // Unknown well-formed events are ignored. The required result is still checked at exit.
  }
}
/** Best-effort known-secret redaction, not a general DLP or filesystem sandbox. */
export function redact(text: string, secrets: string[] = []): string {
  let clean = text.replace(/\x1b\[[0-?]*[ -/]*[@-~]/g, '');
  for (const value of secrets) if (value.length >= 8) clean = clean.split(value).join('[REDACTED]');
  return clean
    .replace(/\b(sk-(?:ant-)?[a-zA-Z0-9_-]{12,})\b/g, '[REDACTED]')
    .replace(/(Bearer\s+)[A-Za-z0-9._~+\/-]{12,}/gi, '$1[REDACTED]');
}
